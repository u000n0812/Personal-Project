#!/usr/bin/env bash
# ===========================================================================
#  사내 지침 챗봇 - 원클릭 자동 설치 (macOS / Linux)
#
#    1) Python 확인
#    2) 가상환경 생성 + 필요한 라이브러리 설치
#    3) Ollama 설치 + LLM 모델 + 임베딩 모델 자동 준비
#    4) 프로그램 실행
#
#  사용법:  ./setup.sh
# ===========================================================================
set -e
cd "$(dirname "$0")"

echo
echo "===================================================================="
echo "  사내 지침 챗봇 - 자동 설치"
echo "===================================================================="
echo
echo "  설치에는 10~30분 정도 걸릴 수 있습니다. (모델 다운로드 포함)"
echo

# --------------------------------------------------------------------
# 1) Python 확인
# --------------------------------------------------------------------
echo "===================================================================="
echo "  [1/4] Python 확인"
echo "===================================================================="

PYTHON=""
for candidate in python3 python; do
  if command -v "$candidate" >/dev/null 2>&1 &&
     "$candidate" -c "import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)" 2>/dev/null; then
    PYTHON="$candidate"
    break
  fi
done

if [ -z "$PYTHON" ]; then
  echo "  Python 3.10 이상이 필요합니다."
  echo
  if [ "$(uname -s)" = "Darwin" ]; then
    echo "  설치:  brew install python@3.11"
    echo "         (Homebrew 가 없으면 https://www.python.org/downloads/ 에서 설치)"
  else
    echo "  설치:  sudo apt install python3 python3-venv python3-pip"
  fi
  exit 1
fi
echo "  설치됨: $($PYTHON --version)"

# --------------------------------------------------------------------
# 2) 가상환경 + 라이브러리
# --------------------------------------------------------------------
echo
echo "===================================================================="
echo "  [2/4] 라이브러리 설치"
echo "===================================================================="

if [ ! -x ".venv/bin/python" ]; then
  echo "  가상환경 생성 중..."
  "$PYTHON" -m venv .venv
fi
VPY=".venv/bin/python"

echo "  필요한 라이브러리 설치 중... (몇 분 걸립니다)"
"$VPY" -m pip install --upgrade pip --quiet
"$VPY" -m pip install -r requirements.txt --quiet
echo "  완료."

# --------------------------------------------------------------------
# 3) Ollama + 모델 자동 준비
# --------------------------------------------------------------------
echo
echo "===================================================================="
echo "  [3/4] AI 모델 준비"
echo "===================================================================="

"$VPY" scripts/setup.py

# --------------------------------------------------------------------
# 4) 실행
# --------------------------------------------------------------------
echo
echo "===================================================================="
echo "  [4/4] 프로그램 실행"
echo "===================================================================="
echo
echo "  브라우저에서 http://127.0.0.1:8501 이 열립니다."
echo "  다음부터는 ./run.sh 로 바로 실행됩니다."
echo

"$VPY" run_app.py
